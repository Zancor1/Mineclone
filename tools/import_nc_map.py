#!/usr/bin/env python3
"""Convert NC or Airshow into an embedded, compressed block-state resource."""
import argparse
import struct,gzip,zlib,pathlib,collections,json
class NBT:
 def __init__(self,b):self.b=b;self.i=0
 def read(self,n):v=self.b[self.i:self.i+n];self.i+=n;return v
 def num(self,f):return struct.unpack('>'+f,self.read(struct.calcsize(f)))[0]
 def text(self):return self.read(self.num('H')).decode('utf8')
 def tag(self,t):
  if t in [1,2,3,4,5,6]:return self.num({1:'b',2:'h',3:'i',4:'q',5:'f',6:'d'}[t])
  if t==7:return self.read(self.num('i'))
  if t==8:return self.text()
  if t==9:
   typ=self.num('B');n=self.num('i');return [self.tag(typ) for _ in range(n)]
  if t==10:
   d={}
   while True:
    typ=self.num('B')
    if typ==0:return d
    name=self.text();d[name]=self.tag(typ)
  if t in [11,12]:return [self.num('i' if t==11 else 'Q') for _ in range(self.num('i'))]
  raise ValueError(t)
 def root(self):t=self.num('B');self.text();return self.tag(t)
def chunks():
 for file in sorted((source/'region').glob('*.mca')):
  b=file.read_bytes()
  for i in range(1024):
   off=int.from_bytes(b[i*4:i*4+3],'big')*4096
   if not off:continue
   length=int.from_bytes(b[off:off+4],'big');data=b[off+5:off+4+length];yield NBT(zlib.decompress(data)).root()['Level']

parser=argparse.ArgumentParser()
parser.add_argument('source',type=pathlib.Path)
parser.add_argument('--output',type=pathlib.Path,default=pathlib.Path('include/nc_map_data.inc'))
parser.add_argument('--airshow',action='store_true')
args=parser.parse_args();source=args.source
from legacy_blocks import convert
records=[];counts=collections.Counter()
for chunk in chunks():
 cx,cz=chunk['xPos'],chunk['zPos']
 if not args.airshow and not(-5<=cx<=5 and -4<=cz<=5):continue
 for section in chunk.get('Sections',[]):
  if not args.airshow and section['Y']*16>=80:continue
  for i,t in enumerate(section['Blocks']):
   if not t or (t==166 and not args.airshow):continue
   x=cx*16+i%16;z=cz*16+(i//16)%16;y=section['Y']*16+i//256
   if not args.airshow and not(-75<=x<=75 and -64<=z<=80 and 5<=y<80):continue
   if args.airshow and not(-120<=x<=120 and -120<=z<=120 and 20<=y<148):continue
   m=(section['Data'][i//2]>>(4*(i%2)))&15
   records.append(bytes([x+128,y-(20 if args.airshow else 5),z+128]+convert(t,m)));counts[t,m]+=1
raw=b''.join(records);compressed=zlib.compress(raw,9)
prefix='Airshow' if args.airshow else 'Nc'
args.output.write_text('// Embedded legacy block states, generated by tools/import_nc_map.py.\n'+f'constexpr unsigned int {prefix}CellCount={len(records)};\nconstexpr unsigned char {prefix}MapData[]={{\n'+''.join('    '+','.join(str(v) for v in compressed[i:i+24])+',\n' for i in range(0,len(compressed),24))+'};\n')
pathlib.Path('data').mkdir(exist_ok=True)
pathlib.Path('data/airshow-import.json' if args.airshow else 'data/nc-import.json').write_text(json.dumps({'name':('Airshow' if args.airshow else 'NC'),'source':source.name,'cells':len(records),'compressed_bytes':len(compressed),'source_offset':[128,-20 if args.airshow else -5,128],'legacy_states':[{'id':k[0],'data':k[1],'count':v} for k,v in sorted(counts.items())]},indent=2)+'\n')
print(f'Imported {len(records)} blocks, {len(counts)} legacy states, {len(compressed)} compressed bytes')
