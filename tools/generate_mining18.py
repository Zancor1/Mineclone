"""Generate mining metadata from the bundled PrismarineJS Minecraft 1.8 data.
Run from the repository root. Tool bits: five picks, five shovels, five swords.
"""
import json
import re
from pathlib import Path
blocks = {b['id']: b for b in json.loads(Path('data/minecraft-1.8/blocks.json').read_text())}
tool_ids = [270,274,257,278,285,269,273,256,277,284,268,272,267,276,283]
materials = {'rock':1,'wood':2,'dirt':3,'wool':4,'leaves':5,'plant':6,'web':7}
entries = {}
for legacy, token in re.findall(r'^\s*\{(\d+),\d+,"[^"]*",(\w+),true\}', Path('include/content18_catalog.inc').read_text(), re.M):
    if int(legacy) < 256 and int(legacy) in blocks:
        entries.setdefault(token, int(legacy))
entries.update(Bed=26, BedHead=26, SpruceLeaves=18, AcaciaPlanks=5, DarkOakPlanks=5,
               LampOn=124, LampOff=123, Kelp=31, MapSlab=44, MapStairs=109,
               MapFence=85, IronBars=101, MapCarpet=171, MapDecoration=50)
lines = ['// Generated by tools/generate_mining18.py; see LICENSES/PrismarineJS-minecraft-data.txt.\n']
for token, legacy in entries.items():
    b = blocks[legacy]
    hard = b.get('hardness')
    hard = -1 if not b.get('diggable', True) or hard is None else hard
    if legacy in [124,123]: hard = .3
    mask = sum(1 << i for i, tool in enumerate(tool_ids) if str(tool) in b.get('harvestTools', {}))
    lines.append(f'    values[{token}]={{{float(hard)}f,{materials.get(b.get("material"),0)},{mask}u}};\n')
Path('include/mining18_properties.inc').write_text(''.join(lines))
